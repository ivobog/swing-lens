def seed_cached_price_facts_copy(engine, symbols, frame, cutoff_at, *, progress):
    """COPY only disposable observed facts, byte-equivalent to seed_price_frame.

    Financial producers, source-manifest validation and sealed writers use their
    normal entry points. Price hashes exclude ticker/date and are generated by
    the production helper for each distinct frame row and feed basis.
    """
    observed = cutoff_at - timedelta(minutes=1)
    prepared = []
    for basis in ("ADJUSTED_LAST", "TRADES"):
        for item in frame.to_dict(orient="records"):
            values = {key: Decimal(str(item[key]))
                      for key in ("open", "high", "low", "close", "volume")}
            row = PriceBar(source="IBKR", what_to_show=basis, adjustment_type=None, **values)
            prepared.append((item["date"].date(), "1 day", *values.values(), "IBKR", basis,
                             None, observed, observed, observed, 0, price_bar_data_hash(row)))
    connection = engine.raw_connection()
    try:
        with connection.driver_connection.cursor() as cursor:
            for offset in range(0, len(symbols), 25):
                with cursor.copy("COPY price_bars (ticker,bar_date,timeframe,open,high,low,close,"
                    "volume,source,what_to_show,adjustment_type,created_at,first_seen_at,"
                    "last_seen_at,revision_count,data_hash) FROM STDIN") as copy:
                    for symbol in symbols[offset:offset + 25]:
                        for values in prepared:
                            copy.write_row((symbol, *values))
                connection.commit()
                progress(
                    "SEED_CACHED_PRICE_FACTS_COPY", min(offset + 25, len(symbols)), len(symbols)
                )
    finally:
        connection.close()


def main(output):
    source = Path(__file__).resolve().parents[1]
    from app.services import sector_universe_service
    assert Path(sector_universe_service.__file__).resolve().is_relative_to(source)
    url = os.environ["SECTOR_SCALE_DATABASE_URL"]
    assert_disposable_database(
        url, active_database_url=os.environ["SECTOR_SCALE_ACTIVE_DATABASE_URL"]
    )
    # A Windows compute worker inherits this environment. It must see only the
    # owned disposable database and must never inherit autonomous live work.
    os.environ.update({
        "DATABASE_URL": url, "JOB_WORKER_ENABLED": "false",
        "WINNER_PROBABILITY_AUTO_MATURATION_ENABLED": "false",
        "WINNER_PROBABILITY_AUTO_COHORT_REFRESH_ENABLED": "false",
        "MARKET_DATA_PREWARM_ENABLED": "false",
        "TECHNICAL_PROCESS_POOL_ENABLED": "true", "TECHNICAL_WORKER_PROCESSES": "1",
        "TECHNICAL_MAX_IN_FLIGHT": "2",
    })
    settings = Settings(
        _env_file=None, database_url=url, ceri_enabled=False, ceri_run_capture_enabled=False,
        ceri_provider_ingest_enabled=False, setup_lifecycle_pipeline_step_enabled=False,
        winner_probability_capture_in_pipeline=False, market_data_prewarm_enabled=False,
        technical_process_pool_enabled=True, technical_worker_processes=1,
        technical_max_in_flight=2, technical_artifact_cache_writes_enabled=False,
        observability_metrics_enabled=False, db_monitor_enabled=False,
    )
    for name in ("app.settings", "app.services.pipeline_service", "app.services.background_worker",
                 "app.services.pipeline_executor", "app.services.technical_score_service"):
        importlib.import_module(name).get_settings = lambda: settings
    import ib_insync

    def forbid_provider(*args, **kwargs):
        raise AssertionError("Live provider calls are forbidden in native scale proof")

    ib_insync.IB.connect = forbid_provider
    ib_insync.IB.connectAsync = forbid_provider
    engine = create_engine(url)
    report = {"started_at": datetime.now(UTC).isoformat(), "source_root": str(source),
        "scope": "Normal admitted 466-company cohort; real sealed producers and Sector writer",
        "provider_calls": 0, "phase": "prepare", "status": "RUNNING", "samples": []}
    report["process_id"] = os.getpid()
    stop = threading.Event()
    guard = threading.Lock()
    peak = {"measured_bytes": 0}

    def sample():
        while not stop.is_set():
            value = process_memory_snapshot()
            measured = value.private_bytes if value.private_bytes is not None else value.rss_bytes
            with guard:
                if measured > peak["measured_bytes"]:
                    peak.update(measured_bytes=measured, rss_bytes=value.rss_bytes,
                        private_bytes=value.private_bytes, phase=report["phase"],
                        observed_at=datetime.now(UTC).isoformat())
            if measured >= BUDGET:
                report.update(status="FAIL_MEMORY_BUDGET", peak_sample=dict(peak),
                              critical_budget_bytes=BUDGET)
                output.write_text(json.dumps(report, indent=2, default=str), encoding="utf-8")
                sys.stderr.write("Isolated native scale child exceeded 6144 MiB; stopping.\n")
                sys.stderr.flush()
                os._exit(74)
            stop.wait(0.05)

    def progress(phase, processed=0, total=0, **kwargs):
        report["phase"] = phase
        report["progress"] = {"processed": processed, "total": total}
        with guard:
            report["peak_sample"] = dict(peak)
        report["updated_at"] = datetime.now(UTC).isoformat()
        output.write_text(json.dumps(report, indent=2, default=str), encoding="utf-8")
        print(f"{phase}: {processed}/{total}", flush=True)
        assert peak["measured_bytes"] < BUDGET, "Native scale process crossed 6144 MiB"

    thread = threading.Thread(target=sample, daemon=True)
    thread.start()
    progress("PREPARING_NORMAL_ADMISSION", 0, 466)
    try:
        with Session(engine, expire_on_commit=False) as db:
            upload = UploadRun(filename="native-466-scale.csv", status="COMPLETED", row_count=466)
            db.add(upload)
            db.flush()
            symbols = tuple(f"SYN{index:04d}" for index in range(466))
            for index, ticker in enumerate(symbols):
                sector, canonical = SECTORS[index % len(SECTORS)]
                db.add(RawCompanyRow(run_id=upload.id, row_number=index + 1, ticker=ticker,
                    sector=sector, sector_canonical=canonical,
                    raw_json={"Symbol": ticker, **_quality_values()}))
            db.flush()
            pipeline = start_pipeline(db, upload.id)
            db.commit()
            cutoff = market_context_for_pipeline(db, pipeline)
            delivery = load_configuration_delivery(
                db, binding_reference(db, pipeline_run_id=pipeline.id)
            )
            profiles = sorted(
                name for name in delivery.configurations if name.startswith("core.ranking:")
            )
            assert len(profiles) == 5
            report["fixture"] = {"companies": 466, "profiles": profiles,
                "price_sessions_per_feed": PRICE_SESSIONS,
                "price_symbols": len(symbols) + len(ETFS),
                "market_context_id": cutoff.context_id, "pipeline_id": pipeline.id,
                "upload_id": upload.id, "cutoff_at": cutoff.cutoff_at,
                "technical_process_pool_enabled": settings.technical_process_pool_enabled,
                "technical_worker_processes": settings.technical_worker_processes,
                "technical_max_in_flight": settings.technical_max_in_flight,
                "technical_v5_enabled": settings.technical_v5_enabled,
                "technical_v5_shadow_compare_enabled": settings.technical_v5_shadow_compare_enabled}
            frame = pd.concat([_synthetic_frame()] * 3, ignore_index=True)
            frame = frame.iloc[:PRICE_SESSIONS].copy()
            frame["date"] = pd.bdate_range(end=cutoff.latest_completed_session, periods=len(frame))
            db.commit()
            seed_cached_price_facts_copy(
                engine, (*symbols, *ETFS), frame, cutoff.cutoff_at, progress=progress
            )
            assert db.scalar(select(func.count()).select_from(PriceBar)) == (
                len((*symbols, *ETFS)) * 2 * PRICE_SESSIONS
            )
            for row in db.scalars(select(PriceBar).limit(10)):
                assert row.data_hash == price_bar_data_hash(row)
            for ticker in symbols:
                db.add(MarketDataSessionDisposition(
                    pipeline_run_id=pipeline.id, upload_run_id=upload.id,
                    market_calculation_context_id=cutoff.context_id, ticker=ticker,
                    expected_session=cutoff.latest_completed_session,
                    latest_bar_session=cutoff.latest_completed_session,
                    **classify_session_readiness(ticker=ticker,
                        expected_session=cutoff.latest_completed_session,
                        latest_bar_session=cutoff.latest_completed_session, lifecycle=None)))
            db.commit()
            with configuration_delivery_scope(delivery):
                def config(name):
                    cls = (ContextualEffectiveConfiguration if name.startswith("contextual.")
                           else CoreEffectiveConfiguration)
                    return cls(delivery.configurations[name].snapshot)

                args = {"market_cutoff": cutoff, "pipeline_run_id": pipeline.id}
                progress("NATIVE_FUNDAMENTALS", 0, 466)
                fundamentals = recalculate_run_fundamentals(db, upload.id, **args,
                    effective_configuration=config("core.fundamental"))
                db.commit()
                pins = {row.ticker: {"fundamental": row.evidence_id} for row in fundamentals}
                del fundamentals
                progress("NATIVE_TECHNICALS", 0, 466)
                technicals = score_run_technicals(db, upload.id, **args, frozen_tickers=symbols,
                    effective_configuration=config("core.technical"), checkpoint_callback=progress)
                db.commit()
                for row in technicals:
                    pins[row.ticker]["technical"] = row.evidence_id
                del technicals
                with engine.connect() as observation:
                    manifests = [dict(row) for row in observation.execute(text(
                        "SELECT source_count,state_count,octet_length(manifest_json::text) "
                        "AS json_text_bytes FROM technical_source_manifests "
                        "WHERE pipeline_run_id=:pipeline AND calculation_context_id=:context"
                    ), {"pipeline": pipeline.id, "context": cutoff.context_id}).mappings()]
                report["technical_manifests"] = manifests
                assert len(manifests) == 1
                assert manifests[0]["state_count"] >= OBSERVED_MANIFEST_STATES
                assert manifests[0]["json_text_bytes"] >= OBSERVED_MANIFEST_JSON_BYTES
                progress("NATIVE_REGIME", 0, 1)
                regime = MarketRegimeCommandCenterService().build_snapshot(db, run_id=upload.id,
                    market_cutoff=cutoff, effective_configuration=config("contextual.regime"))
                db.commit()
                del regime
                progress("NATIVE_COMBINED", 0, 466)
                combined = refresh_combined_results(db, upload.id, **args, source_evidence=pins,
                    effective_configuration=config("core.combined"), checkpoint_callback=progress)
                db.commit()
                del combined
                del pins
                progress("NATIVE_ALL_PROFILE_RANKINGS", 0, 2330)
                rankings = tuple(refresh_all_ranking_profiles(
                    db, upload.id, **args,
                    effective_configurations=tuple(config(name) for name in profiles),
                    checkpoint_callback=progress,
                ))
                assert len(rankings) == 2330
                db.commit()
                del rankings
                with engine.connect() as observation:
                    report["producer_evidence_before_sector"] = [dict(row) for row in (
                        observation.execute(text(
                            "SELECT artifact_kind,count(*) AS rows,"
                            "sum(octet_length(payload_json::text)) AS payload_json_text_bytes "
                            "FROM core_calculation_evidence WHERE run_id=:run "
                            "GROUP BY artifact_kind"
                        ), {"run": upload.id}).mappings()
                    )]
                produced = sum(row["payload_json_text_bytes"]
                               for row in report["producer_evidence_before_sector"])
                report["observed_producer_json_bytes"] = OBSERVED_PRODUCER_JSON_BYTES
                report["producer_json_bytes_before_sector"] = produced
                report["producer_json_size_ratio_to_observed"] = (
                    produced / OBSERVED_PRODUCER_JSON_BYTES
                )
                report["producer_json_at_least_observed"] = produced >= OBSERVED_PRODUCER_JSON_BYTES
                progress("NATIVE_SECTOR_PUBLICATION", 0, 1)
                native_sector_checkpoint = _sector_checkpoint_callback(
                    db, should_cancel=lambda: False, progress_callback=None,
                )

                def sector_progress(**values):
                    native_sector_checkpoint(**values)
                    if values["phase"] in {
                        "INPUTS_LOADED", "SOURCE_ROWS_LOADED", "SOURCE_MANIFEST_PREPARED",
                    }:
                        assert not db.in_transaction()
                        report.setdefault("closed_read_phases", []).append(values["phase"])
                    progress(**values)

                dto = SectorRotationService().build_sector_rotation_snapshot(db, run_id=upload.id,
                    market_cutoff=cutoff, effective_configuration=config("contextual.sector"),
                    checkpoint_callback=sector_progress)
                db.commit()
                assert sum(row.ticker_count for row in dto.universe_rows) == 466
                assert db.scalar(select(func.count()).select_from(SectorRotationSnapshot)) == 1
                stored = list(db.scalars(select(SectorRotationRow).order_by(
                    SectorRotationRow.current_rank)))
                assert len(stored) == len(dto.rows) == 11
                by_sector = {row.sector: row for row in stored}
                for row in dto.rows:
                    assert by_sector[row.sector].sector_final_score == row.final_score
                progress("EXACT_LEGACY_SERIALIZATION_COMPARISON", 0, 1)
                fresh = sector_dataclass_payload(dto)
                old = asdict(dto)
                assert fresh == old
                expected = Canonical.fingerprint(old)
                del old
                gc.collect()
                assert Canonical.fingerprint_streaming(canonical_sector_payload(fresh)) == expected
                report["canonical_fingerprint"] = expected
                report["canonical_and_financial_parity"] = True
                report["published_sector_rows"] = len(stored)
                evidence = db.scalar(select(CoreCalculationEvidence).where(
                    CoreCalculationEvidence.artifact_kind == "SECTOR"
                ))
                sealed_hash = Canonical.fingerprint_streaming(evidence.payload_json)
                dto.debug["native_input_envelope"]["universe_rows"][0]["ticker_count"] = -1
                assert Canonical.fingerprint_streaming(evidence.payload_json) == sealed_hash
                assert sealed_hash == evidence.payload_fingerprint
                report["returned_dto_detached_from_sealed_payload"] = True
                report["evidence"] = [dict(row) for row in db.execute(text(
                    "SELECT artifact_kind,count(*) AS rows,sum(octet_length(payload_json::text)) "
                    "AS payload_json_text_bytes FROM core_calculation_evidence "
                    "GROUP BY artifact_kind"
                )).mappings()]
        report["status"] = "PASS"
        progress("COMPLETED", 1, 1)
    except BaseException as exc:
        report["status"] = "FAIL"
        report["exception_type"] = type(exc).__name__
        raise
    finally:
        stop.set()
        thread.join(5)
        report["peak_sample"] = dict(peak)
        report["critical_budget_bytes"] = BUDGET
        report["finished_at"] = datetime.now(UTC).isoformat()
        output.write_text(json.dumps(report, indent=2, default=str), encoding="utf-8")
        engine.dispose()


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", type=Path, required=True)
    main(parser.parse_args().output)
